CREATE TABLE CONSULTA (
    IDPACIENTE INT,
    IDMEDICO INT,
    DATACONS DATE,
    QUEIXA VARCHAR(30),
    PRESCRICAO VARCHAR(30),
    FOREIGN KEY (IDPACIENTE) REFERENCES PACIENTE(IDPACIENTE),
    FOREIGN KEY (IDMEDICO) REFERENCES MEDICO(IDMEDICO)
);

















