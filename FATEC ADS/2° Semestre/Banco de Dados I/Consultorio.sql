CREATE TABLE MEDICO (
	IDMEDICO INT PRIMARY KEY,
    NOMEMED VARCHAR(6),
    SEXO CHAR(1) check (SEXO='F' or SEXO='M'),
    CRM NUMERIC,
    CODESPEC INT, foreign key(CODESPEC) references ESPECIALIDADE(CODESPEC)
);

